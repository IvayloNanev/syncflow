import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openRequestStore} from '../requests/store.js';
import {analyzeSavedRequest} from '../requests/analyze-saved.js';
import {createFollowUpMockProvider} from '../agents/follow-up/providers/mock.js';
import {buildHandoffSummary} from '../handoff/build-summary.js';
import {reviewRecording} from '../catalog/review.js';

test('acceptance lifecycle: confirm, recheck, handoff save, reviewer completion, reopen and scope-change invalidation',async t=>{
  const fixture=JSON.parse(readFileSync(new URL('../fixtures/development/complete.json',import.meta.url),'utf8').replaceAll('Artist A','Maya Rivers').replaceAll('Track X','Northern Lights'));
  const email=fixture.context.messages[0].text.replace('November 6, 2026.','November 6, 2026 at 17:00 America/Toronto.');
  const deadline=fixture.intake.proposed_changes.find(p=>p.field_key==='response_deadline');
  deadline.proposed_value={supplied_text:'November 6, 2026 at 17:00 America/Toronto',date:'2026-11-06',time:'17:00',timezone:'America/Toronto'};
  deadline.evidence[0].exact_quote=deadline.proposed_value.supplied_text;
  const dir=mkdtempSync(join(tmpdir(),'syncflow-acceptance-'));const path=join(dir,'store.sqlite');let store=openRequestStore(path);
  t.after(()=>{store.close();rmSync(dir,{recursive:true,force:true});});
  const r=store.create({actor_id:'A',email,timezone:'UTC',recording_id:'TRACK-0001',idempotency_key:'create'}).request;
  const providers={intakeProvider:{id:'acceptance',mode:'mock',generate:async({context})=>({schema_version:'1.0',run_id:context.run_id,base_record_version:context.base_record_version,ambiguities:[],proposed_changes:fixture.intake.proposed_changes.filter(p=>!context.confirmed_fields.some(f=>f.field_key===p.field_key)).map(p=>({...p,evidence:p.evidence.map(e=>({...e,message_id:context.messages[0].message_id}))}))})},followUpProvider:createFollowUpMockProvider()};
  const run=await analyzeSavedRequest(store,{actor_id:'A',request_id:r.id,expected_revision:0,idempotency_key:'intake'},providers);
  assert.equal(run.analysis.status,'completed');
  assert.equal(store.workflow('A',r.id).can_complete,false);
  for(const p of run.analysis.result.stages.intake.output.proposed_changes) store.decideProposal({actor_id:'A',request_id:r.id,expected_revision:store.get('A',r.id).revision,run_id:run.analysis.run_id,proposal_id:p.proposal_id,decision:'accept',idempotency_key:`accept-${p.proposal_id}`});
  const current=store.get('A',r.id);
  await analyzeSavedRequest(store,{actor_id:'A',request_id:r.id,expected_revision:current.revision,idempotency_key:'recheck'},providers);
  assert.equal(store.workflow('A',r.id).status,'Needs coordinator review');
  store.approveBrief({actor_id:'A',request_id:r.id,expected_revision:current.revision,analysis_run_id:store.activeAnalysis('A',r.id).run_id,idempotency_key:'brief'});
  assert.equal(store.workflow('A',r.id).status,'Ready for internal review');
  const text=buildHandoffSummary({request:current,analysisCurrent:true,catalog:reviewRecording('TRACK-0001')});
  store.saveHandoff({actor_id:'A',request_id:r.id,expected_revision:current.revision,expected_handoff_version:0,source_token:store.handoff('A',r.id).source_token,text:text+'\nCoordinator note: Verify publishing.',idempotency_key:'handoff'});
  store.recordReview({actor_id:'A',request_id:r.id,expected_revision:current.revision,expected_review_version:0,operation:'assign',name:'Director Demo',role:'Director',idempotency_key:'assign'});
  assert.equal(store.workflow('A',r.id).status,'Internal review pending');
  const reviewer=store.reviewers('A',r.id).reviewers[0];
  store.recordReview({actor_id:'A',request_id:r.id,expected_revision:current.revision,expected_review_version:1,operation:'decision',reviewer_id:reviewer.id,status:'Approved',notes:'Fictional review.',idempotency_key:'approval'});
  const complete={actor_id:'A',request_id:r.id,expected_revision:current.revision,expected_review_version:2,idempotency_key:'complete'};
  store.completeReview(complete);store.completeReview(complete);
  assert.equal(store.workflow('A',r.id).history.length,1);
  store.close();store=openRequestStore(path);
  assert.equal(store.workflow('A',r.id).completed,true);
  assert.match(store.handoff('A',r.id).latest.text,/Coordinator note/);
  store.changeRecording({actor_id:'A',request_id:r.id,expected_revision:current.revision,recording_id:'TRACK-0002',reason:'Fictional version correction',idempotency_key:'recording-change'});
  assert.equal(store.workflow('A',r.id).completed,false);assert.equal(store.activeAnalysis('A',r.id),null);
  assert.deepEqual(store.get('A',r.id).messages,current.messages);
  store.appendReply({actor_id:'A',request_id:r.id,expected_revision:current.revision+1,text:'Actually worldwide.',idempotency_key:'scope-change'});
  assert.equal(store.workflow('A',r.id).completed,false);
  assert.equal(store.workflow('A',r.id).completion.needs_reconfirmation,true);
  assert.equal(store.reviewers('A',r.id).reviewers[0].needs_reconfirmation,true);
  assert.equal(store.handoff('A',r.id).latest.outdated,true);
  assert.equal(store.activeAnalysis('A',r.id),null);
});
