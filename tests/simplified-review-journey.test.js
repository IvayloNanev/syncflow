import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {openRequestStore} from '../requests/store.js';
import {analyzeSavedRequest} from '../requests/analyze-saved.js';
import {createFollowUpMockProvider} from '../agents/follow-up/providers/mock.js';
const fixture=JSON.parse(readFileSync(new URL('../fixtures/development/complete.json',import.meta.url),'utf8').replaceAll('Artist A','Maya Rivers').replaceAll('Track X','Northern Lights'));
const email=fixture.context.messages[0].text.replace('November 6, 2026.','November 6, 2026 at 17:00 America/Toronto.');
const deadline=fixture.intake.proposed_changes.find(p=>p.field_key==='response_deadline');deadline.proposed_value={supplied_text:'November 6, 2026 at 17:00 America/Toronto',date:'2026-11-06',time:'17:00',timezone:'America/Toronto'};deadline.evidence[0].exact_quote=deadline.proposed_value.supplied_text;
const providers=()=>({intakeProvider:{id:'brief-test',mode:'mock',generate:async({context})=>({...structuredClone(fixture.intake),run_id:context.run_id,base_record_version:context.base_record_version,proposed_changes:fixture.intake.proposed_changes.map(p=>({...p,evidence:p.evidence.map(e=>({...e,message_id:context.messages[0].message_id}))}))})},followUpProvider:createFollowUpMockProvider()});
import {storedRoutingCase,canRunCoordinator} from '../server/case-routing-policy.js';
import {caseHandoff,eligibleHandoffs} from '../agents/priority/supervisor.js';
import {managerDecisionToken} from '../requests/manager-decision.js';
import {managerDecisionQuestion,managerDraft} from '../agents/internal/lifecycle.js';
test('documented manager handoff persists, has one owner, resolves and completes without removed gates',async()=>{
 let store=openRequestStore();
 try{
 const r=store.create({actor_id:'A',email,timezone:'UTC',recording_id:'TRACK-0001',idempotency_key:'create'}).request;
 const input={actor_id:'A',request_id:r.id,expected_revision:0,analysis_run_id:'missing',reason:'Budget authority requires a manager decision.',question:'May we proceed within CAD 5,000?',idempotency_key:'send'};
 assert.throws(()=>store.requestInternalReview(input),/REVIEW_NOT_READY/);
 const analyzed=await analyzeSavedRequest(store,{actor_id:'A',request_id:r.id,expected_revision:0,idempotency_key:'analyze'},providers());
 assert.equal(store.workflow('A',r.id).status,'Ready for coordination');
 assert.equal(store.workflow('A',r.id).can_complete,true);
 assert.equal(canRunCoordinator(storedRoutingCase(store,'A',r.id)),true);
 input.analysis_run_id=analyzed.analysis.run_id;
 assert.throws(()=>store.requestInternalReview({...input,reason:''}),/INVALID_INPUT/);
 assert.throws(()=>store.requestInternalReview({...input,expected_revision:1}),/REVISION_CONFLICT/);
 const before=store.get('A',r.id);
 store.requestInternalReview(input);store.requestInternalReview(input);
 const requested=store.get('A',r.id);
 assert.equal(requested.internal_review_history.length,1);
 assert.equal(requested.revision,before.revision);
 assert.deepEqual(requested.messages,before.messages);
 assert.equal(store.activeAnalysis('A',r.id).run_id,input.analysis_run_id);
 assert.equal(store.workflow('A',r.id).can_complete,false);
 const snapshot=store.exportState();store.close();store=openRequestStore(':memory:',{initialState:snapshot});
 const c=storedRoutingCase(store,'A',r.id);
 assert.equal(caseHandoff(c).destination,'internal');assert.equal(eligibleHandoffs(c).length,1);assert.equal(canRunCoordinator(c),false);
 const recommendation={lane:'manager',reason:'Decision needed',escalation_trigger:'Manager decision requested'};
 assert.equal(managerDecisionQuestion(c,recommendation),input.question);
 assert.ok(managerDraft(c,recommendation).body.includes(input.reason));
 const decision={actor_id:'A',request_id:r.id,expected_revision:0,expected_scope_token:managerDecisionToken(c),manager_name:'Synthetic Manager',notes:'Proceed with coordination; obtain all rights approvals before use.',decision:'return_to_coordinator',idempotency_key:'decision'};
 assert.throws(()=>store.recordManagerDecision({...decision,expected_scope_token:'stale'}),/REVISION_CONFLICT/);
 store.recordManagerDecision(decision);
 const returned=storedRoutingCase(store,'A',r.id);
 assert.equal(caseHandoff(returned).destination,'coordinator');assert.equal(eligibleHandoffs(returned).length,1);
 assert.equal(store.get('A',r.id).manager_decision_history.length,1);
 store.setCompleted({actor_id:'A',request_id:r.id,expected_revision:1,completed:true,idempotency_key:'complete'});
 assert.ok(store.get('A',r.id).completed_at);
 store.setDeleted({actor_id:'A',request_id:r.id,expected_revision:1,deleted:true,idempotency_key:'delete'});
 const deleted=store.get('A',r.id);assert.ok(deleted.deleted_at);assert.equal(deleted.messages.length,2);assert.equal(deleted.internal_review_history.length,1);assert.equal(deleted.manager_decision_history.length,1);
 }finally{store.close();}
});
